import { type PalCertErrorCode } from './error-codes.js';

/** Details safe to send to a client (never include stack traces or secrets). */
export type PublicErrorDetails = Record<string, unknown>;

export interface AppErrorOptions {
  /** Human-readable, non-localized message. Safe to expose to clients. */
  readonly message?: string;
  /** HTTP status to use when this error crosses the API boundary. */
  readonly httpStatus?: number;
  /** Structured, client-safe details (e.g. validation issues). */
  readonly details?: PublicErrorDetails;
  /** Internal diagnostic context — logged, never serialized to the client. */
  readonly internalContext?: Record<string, unknown>;
  /** Underlying cause, preserved for logging. */
  readonly cause?: unknown;
}

