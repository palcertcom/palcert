/**
 * The single application error type used across PalCert backend code (§47).
 *
 * Rules:
 *  - `code` + `details` are exposed to clients.
 *  - `internalContext` + `cause` are logged only.
 */
export class AppError extends Error {
  readonly code: PalCertErrorCode;
  readonly httpStatus: number;
  readonly details?: PublicErrorDetails;
  readonly internalContext?: Record<string, unknown>;

  constructor(code: PalCertErrorCode, options: AppErrorOptions = {}) {
    super(options.message ?? code, options.cause !== undefined ? { cause: options.cause } : {});
    this.name = 'AppError';
    this.code = code;
    this.httpStatus = options.httpStatus ?? DEFAULT_HTTP_STATUS[code];
    if (options.details !== undefined) this.details = options.details;
    if (options.internalContext !== undefined) this.internalContext = options.internalContext;
    Error.captureStackTrace?.(this, AppError);
  }

  static isAppError(value: unknown): value is AppError {
    return value instanceof AppError;
  }

  /** Client-safe serialization. Deliberately omits internal context and stack. */
  toPublicJSON(requestId?: string): PublicErrorBody {
    return {
      error: {
        code: this.code,
        message: this.message,
        ...(this.details ? { details: this.details } : {}),
        ...(requestId ? { requestId } : {}),
      },
    };
  }
}

export interface PublicErrorBody {
  error: {
    code: PalCertErrorCode;
    message: string;
    details?: PublicErrorDetails;
    requestId?: string;
  };
}

export function defaultHttpStatusFor(code: PalCertErrorCode): number {
  return DEFAULT_HTTP_STATUS[code];
}
