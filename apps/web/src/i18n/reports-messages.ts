    RECHECKING: 'إعادة الفحص',
    VALIDATING: 'التحقق',
    COMPLETED: 'مكتمل',
    DELIVERED: 'تم التسليم',
    FAILED: 'فشل',
    CANCELLED: 'ملغى',
    EXPIRED: 'منتهي',
    DRAFT: 'مسودة',
    SUBMITTED: 'مقدّم',
